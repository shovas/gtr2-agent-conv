WEIGHTS = {2: [0, 21, 43, 64], 3: [0, 9, 18, 27, 37, 46, 55, 64],
           4: [0, 4, 9, 13, 17, 21, 26, 30, 34, 38, 43, 47, 51, 55, 60, 64]}


def _bits(v: int, pos: int, n: int) -> int:
    if pos >= 128:
        return 0
    return (v >> pos) & ((1 << n) - 1)


def _interpolate(e0: int, e1: int, index: int, index_bits: int) -> int:
    w = WEIGHTS[index_bits][index]
    return ((64 - w) * e0 + w * e1 + 32) >> 6


def decode_block(block: bytes) -> list[tuple[int, int, int, int]] | None:
    """Decode one 16-byte BC7 block to 16 RGBA8 pixels (raster order).

    Reserved blocks (low byte zero) decode to transparent black.
    """
    if len(block) < 16:
        return None
    v = int.from_bytes(block[:16], "little")
    low = v & 0xFF
    if low == 0:
        return [(0, 0, 0, 0)] * 16
    mode = (low & -low).bit_length() - 1  # trailing zeros
    if mode >= 8:
        return [(0, 0, 0, 0)] * 16
    ns, pb, rb, isb, cb, ab, epb, spb, ib, ib2 = MODES[mode]
    pos = mode + 1

    part = _bits(v, pos, pb)
    pos += pb
    rotation = _bits(v, pos, rb)
    pos += rb
    index_select = _bits(v, pos, isb) != 0
    pos += isb

    n_ep = ns * 2
    ep = [[0, 0, 0, 0] for _ in range(6)]
    for ch in range(3):
        for e in range(n_ep):
            ep[e][ch] = _bits(v, pos, cb)
            pos += cb
    if ab > 0:
        for e in range(n_ep):
            ep[e][3] = _bits(v, pos, ab)
            pos += ab

    cprec, aprec = cb, ab
    if epb or spb:
        pbit = [0] * 6
        if epb:
            for p in range(n_ep):
                pbit[p] = _bits(v, pos, 1)
                pos += 1
        else:
            for s in range(ns):
                b = _bits(v, pos, 1)
                pos += 1
                pbit[2*s] = pbit[2*s + 1] = b
        cprec += 1
        for e in range(n_ep):
            for c in range(3):
                ep[e][c] = (ep[e][c] << 1) | pbit[e]
            if ab > 0:
                ep[e][3] = (ep[e][3] << 1) | pbit[e]
        if ab > 0:
            aprec += 1

    for e in range(n_ep):
        for c in range(3):
            ep[e][c] = ((ep[e][c] << (8 - cprec)) | (ep[e][c] >> (2 * cprec - 8))) & 0xFF
        ep[e][3] = (((ep[e][3] << (8 - aprec)) | (ep[e][3] >> (2 * aprec - 8))) & 0xFF
                    if ab > 0 else 255)

    if ns == 1:
        anchors = [0, -1, -1]
    elif ns == 2:
        anchors = [0, ANCHOR2[part], -1]
    else:
        anchors = [0, ANCHOR3_1[part], ANCHOR3_2[part]]

    def subset_of(i: int) -> int:
        if ns == 1:
            return 0
        return PARTITION2[part][i] if ns == 2 else PARTITION3[part][i]

    primary = [0] * 16
    for i in range(16):
        n = ib - 1 if i == anchors[subset_of(i)] else ib
        primary[i] = _bits(v, pos, n)
        pos += n
    secondary = [0] * 16
    if ib2 > 0:
        for i in range(16):
            n = ib2 - 1 if i == 0 else ib2
            secondary[i] = _bits(v, pos, n)
            pos += n

    out = []
    for i in range(16):
        s = subset_of(i)
        e0, e1 = ep[2*s], ep[2*s + 1]
        if ib2 == 0:
            cidx, cbits, aidx, abits = primary[i], ib, primary[i], ib
        elif index_select:
            cidx, cbits, aidx, abits = secondary[i], ib2, primary[i], ib
        else:
            cidx, cbits, aidx, abits = primary[i], ib, secondary[i], ib2
        c = [_interpolate(e0[0], e1[0], cidx, cbits),
             _interpolate(e0[1], e1[1], cidx, cbits),
             _interpolate(e0[2], e1[2], cidx, cbits),
             _interpolate(e0[3], e1[3], aidx, abits)]
        if rotation:
            c[3], c[rotation - 1] = c[rotation - 1], c[3]
        out.append(tuple(x & 0xFF for x in c))
    return out


def decode_bc7(data: bytes, width: int, height: int) -> bytes | None:
    """Decode a BC7 image to RGBA8."""
    bw, bh = max(1, (width + 3) // 4), max(1, (height + 3) // 4)
    if len(data) < bw * bh * 16:
        return None
    out = bytearray()
    for by in range(bh):
        row = [decode_block(data[(by*bw + bx)*16:(by*bw + bx + 1)*16]) for bx in range(bw)]
        for y in range(4):
            for bx in range(bw):
                for x in range(4):
                    if by*4 + y < height and bx*4 + x < width:
                        out.extend(row[bx][y*4 + x])
    return bytes(out)
