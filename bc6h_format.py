def _bits(v: int, src: int, length: int) -> int:
    if src >= 128:
        return 0
    return (v >> src) & ((1 << length) - 1)


def _sign_extend(v: int, bits: int) -> int:
    # Python ints are arbitrary precision, so the C ``v << (32-bits) >> (32-bits)``
    # trick does not sign-extend; flip the sign bit and subtract instead.
    sign = 1 << (bits - 1)
    return (v & ((1 << bits) - 1) ^ sign) - sign


def _unquantize(x: int, bits: int, signed: bool = False) -> int:
    if not signed:
        if bits >= 15:
            return x
        if x == 0:
            return 0
        if x == (1 << bits) - 1:
            return 0xFFFF
        return ((x << 15) + 0x4000) >> (bits - 1)
    if bits >= 16:
        return x
    magnitude = abs(x)
    if magnitude == 0:
        unq = 0
    elif magnitude >= (1 << (bits - 1)) - 1:
        unq = 0x7FFF
    else:
        unq = ((magnitude << 15) + 0x4000) >> (bits - 1)
    return -unq if x < 0 else unq


def _finish(i: int, signed: bool = False) -> int:
    if not signed:
        return ((i * 31) >> 6) & 0xFFFF
    magnitude = ((abs(i) * 31) >> 5) & 0xFFFF
    return magnitude | 0x8000 if (i < 0 and magnitude != 0) else magnitude


def _half_to_unorm8(h: int) -> int:
    """Half-float bit pattern -> 8-bit UNORM, clamped to [0, 1], truncated."""
    if h >= 0x7C00:
        return 255 if h == 0x7C00 else 0
    if h >= 0x3C00:
        return 255
    exp, man = h >> 10, h & 0x3FF
    if exp == 0:
        return (man * 255) >> 24
    return ((1024 + man) * 255) >> (25 - exp)


def decode_block(block: bytes, signed: bool = False) -> list[tuple[int, int, int, int]] | None:
    """Decode one 16-byte BC6H block to 16 RGBA8 pixels (raster order).

    ``signed=True`` selects SF16 instead of UF16. Returns ``None`` for a
    reserved mode.
    """
    if len(block) < 16:
        return None
    v = int.from_bytes(block[:16], "little")
    low2 = v & 3
    mode = low2 if low2 < 2 else (v & 31)
    info = MODE_INFO.get(mode)
    if info is None:
        return None
    transformed, partition, epb, delta_bits = info

    raw = [0] * 12
    for src, length, slot, dst in RUNS[mode]:
        raw[slot] |= _bits(v, src, length) << dst
    n_ep = 4 if partition else 2
    ep = [[0] * 3 for _ in range(4)]  # [endpoint][channel]
    for ch in range(3):
        e0 = _sign_extend(raw[ch * 4], epb) if signed else raw[ch * 4]
        ep[0][ch] = e0
        for k in range(1, n_ep):
            x = raw[ch * 4 + k]
            if transformed:
                x = _sign_extend(x, delta_bits[ch])
                x = (e0 + x) & ((1 << epb) - 1)
                if signed:
                    x = _sign_extend(x, epb)
            elif signed:
                x = _sign_extend(x, epb)
            ep[k][ch] = x
    unq = [[_unquantize(ep[k][ch], epb, signed) for k in range(n_ep)]
           for ch in range(3)]

    if partition:
        part = (v >> 77) & 31
        pa, an = PARTITION2[part], ANCHOR2[part]
        index_bits, index_pos, weights = 3, 82, WEIGHTS3
    else:
        pa, an = [0] * 16, -1
        index_bits, index_pos, weights = 4, 65, WEIGHTS4

    out = []
    pos = index_pos
    for i in range(16):
        n = index_bits - 1 if (i == 0 or i == an) else index_bits
        idx = _bits(v, pos, n)
        pos += n
        subset = pa[i] if partition else 0
        w = weights[idx]
        pixel = tuple(
            _half_to_unorm8(_finish(
                (unq[ch][subset * 2] * (64 - w) + unq[ch][subset * 2 + 1] * w + 32) >> 6,
                signed))
            for ch in range(3))
        out.append((*pixel, 255))
    return out


def decode_bc6h(data: bytes, width: int, height: int, signed: bool = False) -> bytes | None:
    """Decode a BC6H image to RGBA8, or None if any block uses a reserved mode."""
    bw, bh = max(1, (width + 3) // 4), max(1, (height + 3) // 4)
    if len(data) < bw * bh * 16:
        return None
    out = bytearray()
    for by in range(bh):
        row = [decode_block(data[(by * bw + bx) * 16:(by * bw + bx + 1) * 16], signed)
               for bx in range(bw)]
        if any(b is None for b in row):
            return None
        for y in range(4):
            for bx in range(bw):
                for x in range(4):
                    if by * 4 + y < height and bx * 4 + x < width:
                        out.extend(row[bx][y * 4 + x])
    return bytes(out)
